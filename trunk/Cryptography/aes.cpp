  template <int Nk, int Nb, int Nr>
  uint8_t AES<Nk, Nb, Nr>::DOT(uint8_t a, uint8_t b)
  {
    uint8_t p = 0;
    for (int counter = 0; counter < 8; counter++) {
      if ((b & 1) != 0) {
	p ^= a;
      }
      bool hi_bit_set = (a & 0x80) != 0;
      a <<= 1;
      if (hi_bit_set) {
	a ^= 0x1B; /* x^8 + x^4 + x^3 + x + 1 */
      }
      b >>= 1;
    }
    return p;
  }

  template <int Nk, int Nb, int Nr>
  uint8_t AES<Nk, Nb, Nr>::xtime(uint8_t b, int x)
  {
    if (x > 1)
      return AES::xtime((b << 1) ^ 0x1B, x - 1);
    return (b << 1) ^ 0x1B;
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::ADD(WORD a, WORD b, WORD c)
  {
    for (int i = 0; i < AES::WORD_SIZE; i++)
      c[i] = a[i] ^ b[i];
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::MUL(WORD a, WORD b, WORD d)
  {
    for (int i = 0; i < AES::WORD_SIZE; i++) {      
      for (int j = 0; j < AES::WORD_SIZE; j++) {
	d[i] = (AES::DOT(a[(AES::WORD_SIZE - j) % AES::WORD_SIZE], b[j])) ^ d[i];
      }
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::SubBytes(BLOCK s)
  {
    for (int r = 0; r < Nb; r++) {
      for (int c = 0; c < AES::WORD_SIZE; c++) {
	s[r][c] = AES::SBOX[ s[r][c] >> 4 ][ s[r][c] & 0x0F ];
      }
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::ShiftRows(BLOCK s)
  {
    uint8_t tmp;
    for (int c = 1; c < AES::WORD_SIZE; c++) {
      for (int t = 0; t < c; t++) {
	tmp = s[0][c];
	for (int r = 0; r < Nb - 1; r++) {
	  s[r][c] = s[r + 1][c];
	}
	s[Nb - 1][c] = tmp;
      }
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::MixColumns(BLOCK s)
  {
    BLOCK sp;
    for (int r = 0; r < Nb; r++) {
      sp[r][0] = AES::DOT(0x02, s[r][0]) ^ AES::DOT(0x03, s[r][1]) ^ s[r][2] ^ s[r][3];
      sp[r][1] = s[r][0] ^ AES::DOT(0x02, s[r][1]) ^ AES::DOT(0x03, s[r][2]) ^ s[r][3];
      sp[r][2] = s[r][0] ^ s[r][1] ^ AES::DOT(0x02, s[r][2]) ^ AES::DOT(0x03, s[r][3]);
      sp[r][3] = AES::DOT(0x03, s[r][0]) ^ s[r][1] ^ s[r][2] ^ AES::DOT(0x02, s[r][3]);
    }
    std::memmove(s, sp, sizeof(BLOCK));
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::AddRoundKey(BLOCK s, BLOCK w)
  {
    for (int c = 0; c < AES::WORD_SIZE; c++) {
      s[0][c] = s[0][c] ^ w[0][c];
      s[1][c] = s[1][c] ^ w[1][c];
      s[2][c] = s[2][c] ^ w[2][c];
      s[3][c] = s[3][c] ^ w[3][c];
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::Cipher(BLOCK in, SCHEDULE w, BLOCK out)
  {
    std::memcpy(out, in, sizeof(BLOCK));
    AES::AddRoundKey(out, w[0]);
    for (int round = 1; round < Nr; round++) {
      AES::SubBytes(out);
      AES::ShiftRows(out);
      AES::MixColumns(out);
      AES::AddRoundKey(out, w[round]);
    }
    AES::SubBytes(out);
    AES::ShiftRows(out);
    AES::AddRoundKey(out, w[Nr]);
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::Cipher(std::istream& in, schedule_t w, std::ostream& out)
  {
    BLOCK buffer_in, buffer_out;
    while (!in.eof()) {
      in.read((char*)buffer_in, sizeof(BLOCK));
      size_t length = in.gcount();
      if (length < sizeof(BLOCK)) {
	std::memset(((uint8_t*)buffer_in) + length, 0x00, sizeof(BLOCK) - length);
      }
      AES<Nk, Nb, Nr>::Cipher(buffer_in, w, buffer_out);
      out.write((char*)buffer_out, sizeof(BLOCK));
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::SubWord(WORD in, WORD out)
  {
    for (int i = 0; i < AES::WORD_SIZE; i++) {
      out[i] = AES::SBOX[ in[i] >> 4 ][ in[i] & 0x0F ];
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::RotWord(WORD in, WORD out)
  {
    for (int i = 0; i < AES::WORD_SIZE - 1; i++) {
      out[i] = in[i + 1];
    }
    out[AES::WORD_SIZE - 1] = in[0];
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::KeyExpansion(KEY key, SCHEDULE w)
  {
    WORD temp, tmp1;
    std::memcpy(w, key, sizeof(KEY));
    WORD* w_ptr = reinterpret_cast<WORD*>(w);
    for (int i = Nk; i < Nb * (Nr + 1); i++) {
      std::memcpy(temp, w_ptr + i - 1, sizeof(WORD));
      if (i % Nk == 0) {
	AES::RotWord(temp, tmp1);
	AES::SubWord(tmp1, temp);
	temp[0] = temp[0] ^ Rcon[i / Nk];
      } else if (Nk > 6 && i % Nk == 4) {
	AES::SubWord(temp, temp);
      }
      (*(w_ptr + i))[0] = (*(w_ptr + i - Nk))[0] ^ temp[0];
      (*(w_ptr + i))[1] = (*(w_ptr + i - Nk))[1] ^ temp[1];
      (*(w_ptr + i))[2] = (*(w_ptr + i - Nk))[2] ^ temp[2];
      (*(w_ptr + i))[3] = (*(w_ptr + i - Nk))[3] ^ temp[3];
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::InvSubBytes(BLOCK s)
  {
    for (int r = 0; r < Nb; r++) {
      for (int c = 0; c < AES::WORD_SIZE; c++) {
	s[r][c] = AES::ISBOX[ s[r][c] >> 4 ][ s[r][c] & 0x0F ];
      }
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::InvShiftRows(BLOCK s)
  {
    uint8_t tmp;
    for (int c = 1; c < AES::WORD_SIZE; c++) {
      for (int t = 0; t < c; t++) {
	tmp = s[Nb - 1][c];
	for (int r = Nb - 1; r > 0; r--) {
	  s[r][c] = s[r - 1][c];
	}
	s[0][c] = tmp;
      }
    }
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::InvMixColumns(BLOCK s)
  {
    BLOCK sp;
    for (int r = 0; r < Nb; r++) {
      sp[r][0] = AES::DOT(0x0E, s[r][0]) ^ AES::DOT(0x0B, s[r][1]) ^ AES::DOT(0x0D, s[r][2]) ^ AES::DOT(0x09, s[r][3]);
      sp[r][1] = AES::DOT(0x09, s[r][0]) ^ AES::DOT(0x0E, s[r][1]) ^ AES::DOT(0x0B, s[r][2]) ^ AES::DOT(0x0D, s[r][3]);
      sp[r][2] = AES::DOT(0x0D, s[r][0]) ^ AES::DOT(0x09, s[r][1]) ^ AES::DOT(0x0E, s[r][2]) ^ AES::DOT(0x0B, s[r][3]);
      sp[r][3] = AES::DOT(0x0B, s[r][0]) ^ AES::DOT(0x0D, s[r][1]) ^ AES::DOT(0x09, s[r][2]) ^ AES::DOT(0x0E, s[r][3]);
    }
    std::memmove(s, sp, sizeof(BLOCK));
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::InverseCipher(BLOCK in, SCHEDULE w, BLOCK out)
  {
    std::memcpy(out, in, sizeof(BLOCK));
    AES::AddRoundKey(out, w[Nr]);
    for (int round = Nr - 1; round > 0; round--) {
      AES::InvShiftRows(out);
      AES::InvSubBytes(out);
      AES::AddRoundKey(out, w[round]);
      AES::InvMixColumns(out);
    }
    AES::InvShiftRows(out);
    AES::InvSubBytes(out);
    AES::AddRoundKey(out, w[0]);
  }

  template <int Nk, int Nb, int Nr>
  void AES<Nk, Nb, Nr>::InverseCipher(std::istream& in, schedule_t w, std::ostream& out)
  {
    BLOCK buffer_in, buffer_out;
    while (!in.eof()) {
      in.read((char*)buffer_in, sizeof(BLOCK));
      size_t length = in.gcount();
      if (length < sizeof(BLOCK)) {
	std::memset(((uint8_t*)buffer_in) + length, 0x00, sizeof(BLOCK) - length);
      }
      AES<Nk, Nb, Nr>::InverseCipher(buffer_in, w, buffer_out);
      out.write((char*)buffer_out, sizeof(BLOCK));
    }
  }

